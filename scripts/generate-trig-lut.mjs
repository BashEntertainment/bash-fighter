// One-off generator: produces packages/sim/src/math/trigTable.ts as static
// checked-in data. This is the ONLY place Math.sin/Math.cos may be used in
// this repo — packages/sim itself never calls them at runtime, only reads
// the generated integer table. Re-run manually if LUT_SIZE changes.
import { writeFileSync } from 'node:fs';

const LUT_SIZE = 1024; // entries per full turn (2*PI)
const ONE = 1 << 16; // Q16.16 scale

const sinTable = new Array(LUT_SIZE);
const cosTable = new Array(LUT_SIZE);
for (let i = 0; i < LUT_SIZE; i++) {
  const angle = (2 * Math.PI * i) / LUT_SIZE;
  sinTable[i] = Math.round(Math.sin(angle) * ONE) | 0;
  cosTable[i] = Math.round(Math.cos(angle) * ONE) | 0;
}

const header = `// AUTO-GENERATED by scripts/generate-trig-lut.mjs. Do not edit by hand.
// Q16.16 fixed-point sine/cosine lookup tables, LUT_SIZE entries per full turn.
export const LUT_SIZE = ${LUT_SIZE};
export const SIN_LUT: readonly number[] = [${sinTable.join(',')}];
export const COS_LUT: readonly number[] = [${cosTable.join(',')}];
`;

writeFileSync(new URL('../packages/sim/src/math/trigTable.ts', import.meta.url), header);
console.log('wrote trigTable.ts with', LUT_SIZE, 'entries');
